unsigned short PowerTable_Get_Watts(unsigned short SpeedSensorRPM, unsigned short ECB_A_x100)
{
    unsigned char i, Coordinate[_Power_Total], by_Dat;
    unsigned short Value[_Power_Total] = {0};
    unsigned short by_Watts_1, by_Watts_2, by_RPM;
    
    Value[_Power_ECB] = ECB_A_x100;
    Value[_Power_RPM] = SpeedSensorRPM;
    
    if(Value[_Power_RPM] < WattTableInfo[_Power_RPM].InitialValue)
        return 0;
    
    
    for(i=0; i<_Power_Total; i++)
    {
        if(Value[i] <= WattTableInfo[i].InitialValue)
            Coordinate[i] = 0;
        else
        {
            Coordinate[i] = (Value[i] - WattTableInfo[i].InitialValue)/WattTableInfo[i].Graduation;
            if(Coordinate[i] >= WattTableInfo[i].Size)
                Coordinate[i] = WattTableInfo[i].Size - 1;
        }
    }
    
    by_Watts_1 = WattsTable[Coordinate[_Power_RPM]][Coordinate[_Power_ECB]];
    by_Dat = Coordinate[_Power_RPM] >= (WattTableInfo[_Power_RPM].Size - 1) ? Coordinate[_Power_RPM] : (Coordinate[_Power_RPM] + 1);
    by_Watts_2 = WattsTable[by_Dat][Coordinate[_Power_ECB]];
    by_RPM = by_Dat*WattTableInfo[_Power_RPM].Graduation + WattTableInfo[_Power_RPM].InitialValue;
    return (unsigned short)((unsigned long)(by_RPM - SpeedSensorRPM)*(by_Watts_2 - by_Watts_1)/WattTableInfo[_Power_RPM].Graduation + by_Watts_1);
}

